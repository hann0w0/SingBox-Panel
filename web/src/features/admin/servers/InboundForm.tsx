const WS_TYPES = new Set<InboundType>(['vless', 'vmess', 'trojan'])
const REALITY_TYPES = new Set<InboundType>(['vless', 'vmess'])
const TLS_REQUIRED = new Set<InboundType>(['trojan', 'hysteria2', 'tuic', 'anytls'])
const NO_TLS = new Set<InboundType>(['shadowsocks', 'snell', 'socks'])
const HAS_BANDWIDTH = new Set<InboundType>(['hysteria2'])
// Which credential a single-user inbound presents.
const UUID_TYPES = new Set<InboundType>(['vless', 'vmess', 'tuic'])
const PW_TYPES = new Set<InboundType>(['trojan', 'hysteria2', 'anytls', 'tuic'])
const MULTI_USER_TYPES = new Set<InboundType>(['shadowsocks', 'vless', 'anytls', 'vmess', 'tuic', 'trojan', 'hysteria2'])
// Front SNI filter: only the plain TCP VLESS REALITY inbound can put a sniffing
// `direct` relay in front of it without changing the client protocol.
const GUARD_TYPES = new Set<InboundType>(['vless'])
const GUARD_TIMEOUT_RE = /^\+?(?:(?:\d+(?:\.\d*)?|\.\d+)(?:ns|us|µs|μs|ms|s|m|h))+$/
const GUARD_TIMEOUT_PART_RE = /(\d+(?:\.\d*)?|\.\d+)(ns|us|µs|μs|ms|s|m|h)/g
const GUARD_TIMEOUT_SCALE: Record<string, number> = { ns: 1e-9, us: 1e-6, 'µs': 1e-6, 'μs': 1e-6, ms: 1e-3, s: 1, m: 60, h: 3600 }
const GUARD_IPV4_RE = /^(?:\d{1,3}\.){3}\d{1,3}$/

const VMESS_SECURITIES = ['auto', 'none', 'zero', 'aes-128-gcm', 'chacha20-poly1305', 'aes-128-cfb']

type FormVals = Record<string, any>

function parseALPN(value: unknown): string[] | undefined {
  if (typeof value !== 'string') return undefined
  const values = value.split(',').map((item) => item.trim()).filter(Boolean)
  return values.length ? [...new Set(values)] : undefined
}

// parseServerNames splits the comma/space separated editor value into the
// exact SNI list the guard matches on.
export function parseServerNames(value: unknown): string[] | undefined {
  if (typeof value !== 'string') return undefined
  const names = value.split(/[\s,;]+/).map((item) => item.trim()).filter(Boolean)
  return names.length ? [...new Set(names)] : undefined
}

function buildRealityGuard(v: FormVals, type: InboundType, prev?: RealityGuardSettings): RealityGuardSettings | undefined {
  if (!v.guard_enabled || !GUARD_TYPES.has(type) || v.transport_type !== 'tcp') return undefined
  // Invalid enabled settings must reach validation, never silently disable the
  // filter. Preserve an imported tag; new tags are generated by the backend.
  return {
    enabled: true,
    internal_port: Number(v.guard_internal_port || 0),
    server_names: parseServerNames(v.guard_server_names),
    sniff_timeout: String(v.guard_sniff_timeout || '').trim() || undefined,
    ...(prev?.tag ? { tag: prev.tag } : {}),
  }
}

// validGuardServerName mirrors the server-side rule: a full hostname without
// wildcards, ports, IP literals, empty labels or leading/trailing hyphens.
export function validGuardServerName(name: string): boolean {
  if (!name || name.length > 253 || GUARD_IPV4_RE.test(name)) return false
  return name.split('.').every((label) =>
    label.length > 0 &&
    label.length <= 63 &&
    !label.startsWith('-') &&
    !label.endsWith('-') &&
    /^[a-z0-9-]+$/i.test(label),
  )
}

// validateGuardServerNames returns the first user-facing problem, or undefined.
// The whitelist must cover the SNI advertised to subscribers or every client
// would be filtered out before reaching the REALITY inbound.
export function validateGuardServerNames(value: unknown, clientName: unknown): string | undefined {
  const names = parseServerNames(value) || []
  if (!names.length) return undefined
  const invalid = names.find((name) => !validGuardServerName(name))
  if (invalid) return `${invalid} 必须是完整域名，不能包含通配符、端口或 IP`
  const client = typeof clientName === 'string' ? clientName.trim().toLowerCase() : ''
  if (client && !names.some((name) => name.toLowerCase() === client)) {
    return `SNI 白名单必须包含订阅域名 ${clientName}`
  }
  return undefined
}

// validateGuardTimeout accepts the Go duration subset the panel stores.
export function validateGuardTimeout(value: unknown, allowZero = false): string | undefined {
  const text = typeof value === 'string' ? value.trim() : ''
  if (!text || (allowZero && text === '0')) return undefined
  if (!GUARD_TIMEOUT_RE.test(text)) return '请输入时长，例如 300ms'
  let seconds = 0
  for (const match of text.matchAll(GUARD_TIMEOUT_PART_RE)) {
    seconds += Number(match[1]) * (GUARD_TIMEOUT_SCALE[match[2]] ?? 0)
  }
  return seconds > 0 || allowZero ? undefined : '嗅探超时必须大于 0，例如 300ms'
}

function randomPort(): number {
  return Math.floor(Math.random() * 50000) + 10000
}

function supportsMultiUser(type: InboundType, method?: string): boolean {
  if (!MULTI_USER_TYPES.has(type)) return false
  if (type === 'shadowsocks') return (method || '').startsWith('2022-')
  return true
}

